/// 5x5 block glyphs for the title logo.
pub fn glyph(c: char) -> [&'static str; 5] {
    match c {
        'C' => [" ####", "##   ", "##   ", "##   ", " ####"],
        'R' => ["#### ", "##  #", "#### ", "## # ", "##  #"],
        'Y' => ["#   #", " # # ", "  #  ", "  #  ", "  #  "],
        'P' => ["#### ", "##  #", "#### ", "##   ", "##   "],
        'T' => ["#####", "  #  ", "  #  ", "  #  ", "  #  "],
        'S' => [" ####", "##   ", " ### ", "   ##", "#### "],
        'U' => ["#   #", "#   #", "#   #", "#   #", " ### "],
        'N' => ["#   #", "##  #", "# # #", "#  ##", "#   #"],
        'H' => ["#   #", "#   #", "#####", "#   #", "#   #"],
        'O' => [" ### ", "#   #", "#   #", "#   #", " ### "],
        'L' => ["#    ", "#    ", "#    ", "#    ", "#####"],
        _ => ["     ", "     ", "     ", "     ", "     "],
    }
}

